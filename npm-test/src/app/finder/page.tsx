import type { Metadata } from "next";
import Link from "next/link";
import { ArrowUpRight, Wand2 } from "lucide-react";
import { GameFinder } from "@/components/game-finder";
import { GAME_STYLES, OCCASIONS, type GameStyle, type Occasion } from "@/data/games";
import { FINDER_DEFAULTS, type FinderPreferences } from "@/lib/matching";

export const metadata: Metadata = {
  title: "Game finder",
  description:
    "Tell us who is in the room, how much time you have, and what mood you want. Get a transparent shortlist of party games matched to the real catalogue.",
};

const validTimes = [15, 30, 45, 60, 120] as const;

function readPreferences(params: { [key: string]: string | string[] | undefined }): FinderPreferences {
  const value = (key: string): string => {
    const item = params[key];
    return typeof item === "string" ? item : "";
  };

  const occasion = value("occasion");
  const ageGroup = value("ageGroup");
  const format = value("format");
  const style = value("style");
  const minutes = Number(value("minutes"));
  const players = Number(value("players"));

  return {
    occasion: OCCASIONS.includes(occasion as Occasion) ? (occasion as Occasion) : FINDER_DEFAULTS.occasion,
    players: Number.isFinite(players) && players >= 2 && players <= 30 ? Math.round(players) : FINDER_DEFAULTS.players,
    ageGroup: ["8", "13", "18"].includes(ageGroup) ? (ageGroup as FinderPreferences["ageGroup"]) : FINDER_DEFAULTS.ageGroup,
    minutes: validTimes.includes(minutes as (typeof validTimes)[number]) ? (minutes as FinderPreferences["minutes"]) : FINDER_DEFAULTS.minutes,
    format: ["all", "offline", "online"].includes(format) ? (format as FinderPreferences["format"]) : FINDER_DEFAULTS.format,
    style: GAME_STYLES.includes(style as GameStyle) ? (style as GameStyle) : FINDER_DEFAULTS.style,
  };
}

export default async function FinderPage({
  searchParams,
}: {
  searchParams: Promise<{ [key: string]: string | string[] | undefined }>;
}) {
  const params = await searchParams;
  const initialPreferences = readPreferences(params);

  return (
    <>
      <section className="relative overflow-hidden border-b border-line/70 pb-10 pt-12 sm:pb-12 sm:pt-16">
        <div
          aria-hidden="true"
          className="pointer-events-none absolute -left-28 top-8 h-80 w-80 rounded-full bg-terracotta/10 blur-3xl"
        />
        <div className="shell relative">
          <div className="grid gap-8 lg:grid-cols-[1fr_auto] lg:items-end">
            <div className="max-w-2xl">
              <div className="flex items-center gap-3">
                <Wand2 className="h-4 w-4 text-terracotta" aria-hidden="true" />
                <p className="eyebrow">The game finder</p>
              </div>
              <h1 className="text-display-sm mt-4">
                A shortlist,
                <br />
                <span className="italic text-terracotta">not a slot machine.</span>
              </h1>
              <p className="mt-5 max-w-xl text-base leading-relaxed text-ink-soft">
                Tell us who&apos;s there and what the room needs. We&apos;ll filter the real
                catalogue and explain every recommendation. No account required.
              </p>
            </div>
            <div className="lg:pb-1">
              <p className="max-w-[16rem] text-xs leading-relaxed text-ink-faint">
                Every game is tagged for players, age, time, occasion, and mood. Nothing here is
                generated by an AI service.
              </p>
              <Link
                href="/games"
                className="mt-3 inline-flex min-h-10 items-center gap-1.5 text-xs font-bold text-forest underline decoration-forest/25 underline-offset-4 hover:decoration-forest"
              >
                Or browse the full shelf
                <ArrowUpRight className="h-3.5 w-3.5" aria-hidden="true" />
              </Link>
            </div>
          </div>
        </div>
      </section>

      <section className="py-9 sm:py-12">
        <div className="shell">
          <GameFinder initialPreferences={initialPreferences} />
        </div>
      </section>
    </>
  );
}
