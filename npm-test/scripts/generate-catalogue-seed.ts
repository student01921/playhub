import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { games } from "../src/data/games";
import { triviaQuestions } from "../src/data/trivia-questions";

const root = resolve(process.cwd());

function sqlText(value: string | null | undefined): string {
  if (value === null || value === undefined) return "null";
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlJson(value: unknown): string {
  return `${sqlText(JSON.stringify(value))}::jsonb`;
}

function sqlTextArray(values: readonly string[]): string {
  if (values.length === 0) return "'{}'::text[]";
  return `array[${values.map(sqlText).join(", ")}]::text[]`;
}

function gameValues(game: (typeof games)[number]): string {
  return `(
    ${sqlText(game.slug)},
    ${sqlText(game.title)},
    ${sqlText(game.tagline)},
    ${sqlText(game.description)},
    ${sqlText(game.type)},
    'offline',
    ${game.minPlayers},
    ${game.maxPlayers},
    ${game.minAge},
    ${game.durationMinutes},
    ${sqlTextArray(game.occasions)},
    ${sqlTextArray(game.styles)},
    ${sqlTextArray(game.materials)},
    ${sqlText(game.setup)},
    ${sqlJson(game.rules)},
    ${sqlText(game.howToWin)},
    ${sqlJson(game.variations)},
    ${sqlText(game.hostTip)},
    ${sqlText(game.difficulty)},
    ${sqlText(game.artTheme)},
    ${game.featured ? "true" : "false"}
  )`;
}

const gameColumns = [
  "slug",
  "title",
  "short_description",
  "description",
  "game_type",
  "format",
  "min_players",
  "max_players",
  "min_age",
  "estimated_duration_minutes",
  "occasions",
  "styles",
  "materials",
  "setup",
  "rules",
  "how_to_win",
  "variations",
  "host_tip",
  "difficulty",
  "art_theme",
  "featured",
].join(", ");

const gameUpdates = [
  "title = excluded.title",
  "short_description = excluded.short_description",
  "description = excluded.description",
  "game_type = excluded.game_type",
  "format = excluded.format",
  "min_players = excluded.min_players",
  "max_players = excluded.max_players",
  "min_age = excluded.min_age",
  "estimated_duration_minutes = excluded.estimated_duration_minutes",
  "occasions = excluded.occasions",
  "styles = excluded.styles",
  "materials = excluded.materials",
  "setup = excluded.setup",
  "rules = excluded.rules",
  "how_to_win = excluded.how_to_win",
  "variations = excluded.variations",
  "host_tip = excluded.host_tip",
  "difficulty = excluded.difficulty",
  "art_theme = excluded.art_theme",
  "featured = excluded.featured",
].join(",\n    ");

const questionValues = triviaQuestions
  .map(
    (question) => `(
    ${sqlText(question.question)},
    ${sqlText(question.category)},
    ${sqlText(question.difficulty)},
    ${sqlJson(question.options)},
    ${question.correctOptionIndex},
    ${sqlText(question.explanation)},
    true
  )`,
  )
  .join(",\n  ");

const sql = `-- GatherPlay catalogue seed — generated by npm run generate:seed.
-- Do not edit by hand. Update src/data/games.ts or src/data/trivia-questions.ts.
--
-- Both statements are upserts, so this file is safe to run more than once.
-- Correct trivia answers live here and in the private questions table only.
-- The browser-facing SQL functions remove them until the reveal phase.

begin;

insert into public.games (${gameColumns})
values
  ${games.map(gameValues).join(",\n  ")}
on conflict (slug) do update set
    ${gameUpdates};

insert into public.trivia_questions (
  question,
  category,
  difficulty,
  options,
  correct_option_index,
  explanation,
  is_active
)
values
  ${questionValues}
on conflict (question) do update set
  category = excluded.category,
  difficulty = excluded.difficulty,
  options = excluded.options,
  correct_option_index = excluded.correct_option_index,
  explanation = excluded.explanation,
  is_active = excluded.is_active;

commit;
`;

const migrationPath = resolve(root, "supabase/migrations/20261027000200_catalogue_seed.sql");
const seedPath = resolve(root, "supabase/seed.sql");

mkdirSync(dirname(migrationPath), { recursive: true });
writeFileSync(migrationPath, sql, "utf8");
writeFileSync(
  seedPath,
  `-- Local development seed. Generated by npm run generate:seed.\n-- The same upserts are applied automatically by the catalogue migration.\n\n${sql.replace(
    "-- GatherPlay catalogue seed — generated by npm run generate:seed.\n-- Do not edit by hand. Update src/data/games.ts or src/data/trivia-questions.ts.\n--\n-- Both statements are upserts, so this file is safe to run more than once.\n-- Correct trivia answers live here and in the private questions table only.\n-- The browser-facing SQL functions remove them until the reveal phase.\n\n",
    "",
  )}`,
  "utf8",
);

console.log(
  `Wrote ${games.length} games and ${triviaQuestions.length} trivia questions to the catalogue migration and seed.sql.`,
);
